// "auto" → by the language of leaders' replies (cfg.language): Russian → ru, anything else → en
export function uiLang(cfg) {
  const v = String(cfg?.ui_language || 'auto').toLowerCase();
  if (S[v]) return v;
  return /рус|russ|^ru/i.test(String(cfg?.language || '')) ? 'ru' : 'en';
}

export function makeT(lang) {
  const d = S[lang] || S.en;
  return (key, p = {}) => {
    const v = d[key] ?? S.en[key];
    if (v === undefined) return key;
    return typeof v === 'function' ? v(p) : v;
  };
}
